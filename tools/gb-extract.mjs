#!/usr/bin/env node
// Extract Game Boy timbre data from local disassemblies into a LOCAL module
// (src/engine/instruments/gbdata.game.js, gitignored: it is game data, not ours
// to publish). Only timbres are extracted -- wave-channel tables and noise
// drum register sequences -- never song note data.
//
//   node tools/gb-extract.mjs [--crystal <pokecrystal dir>] [--oracles <oracles-disasm dir>]
import { readFileSync, writeFileSync } from 'node:fs';
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const CRYSTAL = arg('--crystal', '/Users/slowbro/workspaces/pokemon-resources/decomps/pokecrystal');
const ORACLES = arg('--oracles', '/Users/slowbro/workspaces/zelda-resources/decomps/oracles');
const out = { source: {}, waves: {}, drums: {}, oraclesNoise: [] };

// --- Pokemon Crystal: wave samples (dn = 32 nybbles) ---
{
  const s = readFileSync(`${CRYSTAL}/audio/wave_samples.asm`, 'utf8');
  const rows = [...s.matchAll(/^\s*dn\s+([\d,\s]+)$/gm)].map(m => m[1].split(',').map(x => Number(x.trim())));
  rows.forEach((r, i) => { if (r.length === 32) out.waves[`crystal:${i}`] = r; });
  out.source.crystalWaves = rows.length;
}
// --- Pokemon Crystal: drum instruments (noise_note length, vol, env, nr43) ---
{
  const s = readFileSync(`${CRYSTAL}/audio/drumkits.asm`, 'utf8');
  let cur = null;
  for (const line of s.split('\n')) {
    const lab = /^(\w+):\s*$/.exec(line);
    if (lab) { cur = lab[1]; if (!/^Drumkit/.test(cur)) out.drums[`crystal:${cur}`] = []; continue; }
    const m = /noise_note\s+(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)/.exec(line);
    if (m && cur && out.drums[`crystal:${cur}`]) {
      const [len, vol, env, nr43] = m.slice(1).map(Number);
      out.drums[`crystal:${cur}`].push({ frames: (len & 15) + 1, vol, envUp: env < 0, envPeriod: Math.abs(env) & 7, nr43 });
    }
  }
  for (const k of Object.keys(out.drums)) if (!out.drums[k].length) delete out.drums[k];
  out.source.crystalDrums = Object.keys(out.drums).length;
}
// --- Oracles: waveforms (.db 16 bytes = 32 nybbles) and the noise table ---
{
  const s = readFileSync(`${ORACLES}/audio/common/waveforms.s`, 'utf8');
  const re = /m_waveform\s+\$([0-9a-f]+),\s*(\w+)\s*\n\s*\.db\s+([$0-9a-f\s]+)/gi;
  let m, n = 0;
  while ((m = re.exec(s))) {
    const bytes = m[3].trim().split(/\s+/).map(x => parseInt(x.replace('$', ''), 16));
    if (bytes.length !== 16) continue;
    out.waves[`oracles:${m[1]}:${m[2]}`] = bytes.flatMap(b => [b >> 4, b & 15]); n++;
  }
  out.source.oraclesWaves = n;
  const ns = readFileSync(`${ORACLES}/audio/common/noise.s`, 'utf8');
  for (const r of ns.matchAll(/^\s*\.db\s+\$([0-9a-f]{2})\s+\$([0-9a-f]{2})\s+\$([0-9a-f]{2})/gim)) {
    const nr42 = parseInt(r[2], 16);
    out.oraclesNoise.push({ note: parseInt(r[1], 16), envUp: !!(nr42 & 8), envPeriod: nr42 & 7, nr43: parseInt(r[3], 16) });
  }
  out.source.oraclesNoise = out.oraclesNoise.length;
}
const dest = new URL('../src/engine/instruments/gbdata.game.js', import.meta.url);
writeFileSync(dest, `// GENERATED by tools/gb-extract.mjs from local disassemblies. Game data: do not commit.\nexport default ${JSON.stringify(out)};\n`);
console.log(JSON.stringify(out.source), '->', dest.pathname);
